/* ==========================================================================
   story.js — УВЕСЬ ТЕКСТ КНИГИ в одному місці.
   Тут немає жодної логіки: лише історія, розбори, схеми й приклади коду.
   Малює це все js/book.js. Хочеш змінити книгу — міняй тільки цей файл.

   Блоки, з яких складається розділ:
     {t:'story',   p:[...]}                 — абзаци історії
     {t:'max',     p:[...]}                 — голос Макса (записка на полях)
     {t:'postcard',from, stamp, p:[...]}    — листівка від Цугі
     {t:'pull',    html}                    — виділена думка
     {t:'journal', title, blocks:[...]}     — сторінка журналу (паперовий блок)
     {t:'h3'|'p'|'small', text|html}        — заголовок / абзац / дрібний текст
     {t:'list',    ordered, items:[...]}    — список
     {t:'anatomy', tokens:[{k,glyph,cap}]}  — розбір команди на частини
     {t:'diagram', label, svg, caption}     — блок-схема
     {t:'legend',  items:[{chip,text}]}     — легенда фігур
     {t:'sb',      title, code, night}     — пісочниця з Python (night — показати банку «ніч»)
     {t:'task',    id, kind, goal, code,
                   hints, solution, checks} — завдання; kind:'fix' = плашка «Полагодь»
     {t:'applied', title, html}             — завдання «У житті»
     {t:'gist',    html}                    — «Коротше кажучи»: думка в одному реченні
     {t:'word',    term, html}              — слово на полях (гніт, лінза, каністра…)
     {t:'bridge',  pairs:[[наше,їхнє,нота]]}— міст до справжнього Python
     {t:'debug',   steps:[...], html}       — картка «Коли не працює»
     {t:'secret',  title, p:[...]}          — секретна сторінка
     {t:'progress'}                         — журнал завдань
     {t:'cta',     href, text}              — кнопка наприкінці
   ========================================================================== */

